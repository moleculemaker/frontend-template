#!/usr/bin/env node
// TypeScript types for this app's job input and results, from the tool's JSON Schemas.
//
//   npm run schemas                 regenerate src/app/api/tool-schemas.ts from schemas/
//   npm run schemas -- --check      exit 1 if it is out of date (CI runs this)
//   npm run schemas:sync            fetch the schemas for app.yaml's job_type from the
//                                   staging backend first (--api <url> for another one)
//
// The backend is the source of truth for both schemas (mmli-backend
// app/schemas/<tool>.input.json and .output.json); schemas/ holds the copy this app
// was built against, so a build never depends on the network. The template's copies
// are the sample tool's, from moleculemaker/job-template.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import { parse } from 'yaml';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const STAGING_API = 'https://mmli.fastapi.staging.mmli2.ncsa.illinois.edu/v1';
const SCHEMAS = { input: 'schemas/input.schema.json', output: 'schemas/output.schema.json' };
const OUTPUT = 'src/app/api/tool-schemas.ts';

const read = (path) => readFileSync(join(ROOT, path), 'utf8');

async function fetchJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

// The tool's descriptor links to both schemas; a tool without an output schema is not
// on the backend's generic job contract, and this flow does not support it.
async function sync(api) {
  const tool = parse(read('app.yaml')).job_type;
  if (!tool) throw new Error('app.yaml has no job_type: set it to the tool registered in mmli-backend');
  const { links } = await fetchJson(`${api}/tools/${tool}`);
  if (!links.input_schema || !links.output_schema) {
    throw new Error(`${tool} publishes no ${links.input_schema ? 'output' : 'input'} schema`);
  }
  for (const [kind, link] of [['input', links.input_schema], ['output', links.output_schema]]) {
    // $id names the host it was served from; the copy is the same document wherever it
    // came from.
    const { $id, ...schema } = await fetchJson(link);
    writeFileSync(join(ROOT, SCHEMAS[kind]), JSON.stringify(schema, null, 2) + '\n');
  }
}

// The interface names are fixed, so app code doesn't change with the tool: compile()
// would otherwise name each one after its schema's title. Item counts stay out of the
// types (they would become tuples); the backend enforces them.
export async function generate(readSchema = (path) => JSON.parse(read(path))) {
  const options = { bannerComment: '', additionalProperties: false, ignoreMinAndMaxItems: true };
  const named = (schema, title) => ({ ...schema, title });
  const input = await compile(named(readSchema(SCHEMAS.input), 'ToolInput'), 'ToolInput', options);
  const output = await compile(named(readSchema(SCHEMAS.output), 'ToolResults'), 'ToolResults', options);
  return [
    '// Generated by `npm run schemas` from schemas/. Do not edit.',
    '',
    input.trim(),
    '',
    output.trim(),
    '',
  ].join('\n');
}

async function main(args) {
  if (args.includes('--sync')) {
    const at = args.indexOf('--api');
    await sync(at >= 0 ? args[at + 1] : STAGING_API);
  }
  const generated = await generate();
  if (args.includes('--check')) {
    let current = '';
    try { current = read(OUTPUT); } catch { /* missing counts as out of date */ }
    if (current !== generated) {
      console.error(`${OUTPUT} is out of date with schemas/. Run \`npm run schemas\`.`);
      process.exit(1);
    }
    return;
  }
  writeFileSync(join(ROOT, OUTPUT), generated);
  console.log(`wrote ${OUTPUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
